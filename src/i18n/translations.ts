export const translations: Record<AppLanguage, Record<TranslationKey, string>> =
  semanticTranslations;

const phraseTranslations: Record<AppLanguage, Record<string, string>> = {
  ar: arCopy,
  en: enCopy,
  fr: {},
};

let activeLanguage: AppLanguage = 'fr';

export function normalizeLanguage(value: unknown): AppLanguage {
  return value === 'ar' || value === 'en' || value === 'fr' ? value : 'fr';
}

export function setActiveLanguage(language: AppLanguage) {
  activeLanguage = language;
}

export function getActiveLanguage() {
  return activeLanguage;
}

export function getIntlLocale(language = activeLanguage) {
  return intlLocales[language];
}

export function translatePhrase(language: AppLanguage, value: string) {
  if (language === 'fr') {
    return value;
  }

  return phraseTranslations[language][value] ?? value;
}

export function translateActivePhrase(value: string) {
  return translatePhrase(activeLanguage, value);
}
